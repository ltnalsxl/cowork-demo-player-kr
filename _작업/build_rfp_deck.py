def layout(prs, name):
    for m in prs.slide_masters:
        for l in m.slide_layouts:
            if l.name == name:
                return l
    raise KeyError(name)


def add(prs, name):
    return prs.slides.add_slide(layout(prs, name))


def ph(slide, idx):
    for p in slide.placeholders:
        if p.placeholder_format.idx == idx:
            return p
    return None


def body(slide, idx, lines):
    """(글머리 수준, 문장) 목록을 개체 틀에 넣는다."""
    tf = ph(slide, idx).text_frame
    tf.clear()
    for i, (lv, text) in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = text
        p.level = lv


def drop_empty(slide):
    for p in list(slide.placeholders):
        if p.has_text_frame and not p.text_frame.text.strip():
            p._element.getparent().remove(p._element)


def title(slide, text):
    ph(slide, 0).text_frame.text = text


def new(tpl=TPL):
    prs = Presentation(tpl)
    for sid in list(prs.slides._sldIdLst):
        prs.slides._sldIdLst.remove(sid)
    return prs


def cover(prs, sub):
    s = add(prs, '표지')
    title(s, '「공공 AI사업 추진체계 유연화 방안 마련」 제안요약서')
    ph(s, 1).text_frame.text = sub
    return s


def closing(prs, sub):
    s = add(prs, '마무리')
    title(s, '감사합니다')
    p = ph(s, 1)
    if p is not None:
        p.text_frame.text = sub
    return s


def table_slide(prs, head, rows):
    """표 한 판 레이아웃. 대화 기록에 남은 좌표를 그대로 쓴다."""
    s = add(prs, '표 한 판')
    shp = s.shapes.add_table(len(rows) + 1, len(head),
                             Inches(0.72), Inches(1.74),
                             Inches(11.89), Inches(0.4 * (len(rows) + 1)))
    t = shp.table
    for c, v in enumerate(head):
        t.cell(0, c).text = v
    for r, row in enumerate(rows, 1):
        for c, v in enumerate(row):
            t.cell(r, c).text = v
    return s


