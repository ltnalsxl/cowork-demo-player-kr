def set_cell(cell, text):
    """셀 텍스트만 바꾸고 서식은 첫 run에 맡긴다."""
    ps = [p for p in cell.paragraphs if p.text.strip()] or cell.paragraphs
    p = ps[0]
    if p.runs:
        p.runs[0].text = text
        for r in p.runs[1:]:
            r.text = ''
    else:
        p.text = text
    for extra in ps[1:]:
        for r in extra.runs:
            r.text = ''


def set_para(p, text):
    if p.runs:
        p.runs[0].text = text
        for r in p.runs[1:]:
            r.text = ''
    else:
        p.text = text


def main():
    shutil.copy2(ORIG, SRC)
    d = docx.Document(SRC)

    # 문단은 본문 순서대로 대응시킨다.
    paras = [Paragraph(c, d) for c in d.element.body.iterchildren()
             if c.tag == ns.qn('w:p')]
    if len(paras) != len(PARAS):
        raise SystemExit('문단 수 불일치: 원본 %d, 준비 %d' % (len(paras), len(PARAS)))
    for p, txt in zip(paras, PARAS):
        if txt:
            set_para(p, txt)

    if len(d.tables) != len(TABLES):
        raise SystemExit('표 수 불일치')
    for t, data in zip(d.tables, TABLES):
        for row, vals in zip(t.rows, data):
            for cell, v in zip(row.cells, vals):
                if v is not None:
                    set_cell(cell, v)

    cp = d.core_properties
    cp.author = 'Copilot User'
    cp.last_modified_by = 'Copilot User'
    cp.title = '주간 업무보고'
    cp.comments = ''
    d.save(SRC)
    print('재작성 완료: 문단 %d, 표 %d' % (len(paras), len(d.tables)))


if __name__ == '__main__':
    main()

